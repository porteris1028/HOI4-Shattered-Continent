#!/usr/bin/env python3
"""Generate every per-nation file from setup/nations.toml.

    python3 tools/build_nations.py

Writes (and overwrites):
  common/country_tags/sc_countries.txt
  common/countries/SC <Name>.txt
  history/countries/<TAG> - <Name>.txt
  common/characters/sc_characters.txt
  common/scripted_effects/sc_generated_armies.txt
  localisation/english/sc_nations_l_english.yml
  gfx/flags/<TAG>.tga  (+ medium/, small/)  unless gfx/flags/custom/<TAG>.tga exists
  docs/NATIONS.md

Needs Python 3.11+ and Pillow (pip install pillow).
"""
import re
import sys
import tomllib
from pathlib import Path

try:
    from PIL import Image, ImageDraw
except ImportError:
    sys.exit("Needs Pillow: pip install pillow")

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "setup" / "nations.toml"
GEN = "# GENERATED by tools/build_nations.py from setup/nations.toml - edit that file instead.\n"

IDEOLOGIES = ["democratic", "communism", "fascism", "neutrality"]
DEFAULT_SUB = {"democratic": "liberalism", "communism": "marxism", "fascism": "nazism", "neutrality": "despotism"}
TECH_PRESETS = {
    "basic": ["infantry_weapons", "infantry_weapons1", "tech_support", "tech_recon"],
    "veteran": ["infantry_weapons", "infantry_weapons1", "infantry_weapons2", "tech_support", "tech_recon",
                "tech_engineers", "gw_artillery", "interwar_artillery"],
}
TECH_PRESETS["mountain"] = TECH_PRESETS["veteran"] + ["tech_mountaineers"]
UNIT_TECH = {
    "mountaineers": ["tech_mountaineers"], "engineer": ["tech_support", "tech_engineers"],
    "recon": ["tech_support", "tech_recon"], "artillery": ["tech_support", "gw_artillery"],
    "artillery_brigade": ["gw_artillery"], "military_police": ["tech_support", "tech_military_police"],
    "motorized": ["motorised_infantry"],
}
REQUIRED = ["tag", "name", "ideology", "color"]


def esc(s):
    """Make a string safe for a HoI4 localisation line."""
    return str(s).replace("\n", "\\n")


def safe_filename(name):
    return re.sub(r"[^A-Za-z0-9 ]", "", name).strip()


def validate(nations):
    problems, tags = [], set()
    for n in nations:
        for k in REQUIRED:
            if k not in n:
                problems.append(f"{n.get('tag', '?')}: missing '{k}'")
        tag = n.get("tag", "")
        if not re.fullmatch(r"[A-Z]{3}", tag):
            problems.append(f"{tag}: tag must be 3 capital letters")
        if tag in tags:
            problems.append(f"{tag}: duplicate tag")
        tags.add(tag)
        if n.get("ideology") not in IDEOLOGIES:
            problems.append(f"{tag}: ideology must be one of {IDEOLOGIES}")
        pops = n.get("popularities")
        if pops and sum(pops.values()) != 100:
            problems.append(f"{tag}: popularities add up to {sum(pops.values())}, not 100")
        if n.get("divisions") and not n.get("template"):
            problems.append(f"{tag}: has divisions but no template")
    if problems:
        sys.exit("nations.toml problems:\n  " + "\n  ".join(problems))


def template_block(t):
    lines = [f'division_template = {{', f'\tname = "{t["name"]}"', "\tregiments = {"]
    col, by_type = 0, {}
    for r in t.get("regiments", []):
        by_type.setdefault(r, []).append(r)
    for unit, items in by_type.items():
        for i in range(0, len(items), 5):
            for y, _ in enumerate(items[i:i + 5]):
                lines.append(f"\t\t{unit} = {{ x = {col} y = {y} }}")
            col += 1
    lines.append("\t}")
    if t.get("support"):
        lines.append("\tsupport = {")
        for y, s in enumerate(t["support"]):
            lines.append(f"\t\t{s} = {{ x = 0 y = {y} }}")
        lines.append("\t}")
    lines.append("}")
    return "\n".join(lines)


def techs_for(n):
    techs = list(TECH_PRESETS[n.get("tech", "basic")])
    t = n.get("template", {})
    for unit in t.get("regiments", []) + t.get("support", []):
        techs += UNIT_TECH.get(unit, [])
    return list(dict.fromkeys(techs))


def history(n):
    ide = n["ideology"]
    pops = n.get("popularities", {ide: 100})
    elections = n.get("elections", False)
    out = [GEN, f"# {n['name']} ({n.get('group', '')})",
           "capital = 1   # real capital is set at game start from setup/state_assignments.csv",
           f"set_research_slots = {n.get('research_slots', 2)}",
           f"set_stability = {n.get('stability', 0.5)}",
           f"set_war_support = {n.get('war_support', 0.5)}",
           "set_politics = {",
           f"\truling_party = {ide}",
           f'\tlast_election = "{"1945.6.1" if elections else "1936.1.1"}"',
           f"\telection_frequency = 48",
           f"\telections_allowed = {'yes' if elections else 'no'}",
           "}",
           "set_popularities = { " + " ".join(f"{i} = {pops.get(i, 0)}" for i in IDEOLOGIES) + " }"]
    if n.get("leader"):
        out.append(f"recruit_character = {n['leader']['key']}")
    if n["tag"] != "WST":
        out.append("set_technology = {\n" + "\n".join(f"\t{t} = 1" for t in techs_for(n)) + "\n}")
    if n.get("template"):
        out.append(template_block(n["template"]))
    if n.get("equipment", 2000) and n["tag"] != "WST":
        out.append(f"add_equipment_to_stockpile = {{ type = infantry_equipment_1 amount = {n.get('equipment', 2000)} producer = {n['tag']} }}")
    if n.get("ideas"):
        out.append("add_ideas = { " + " ".join(n["ideas"]) + " }")
    for f in n.get("country_flags", []):
        out.append(f"set_country_flag = {f}")
    if n.get("nomadic"):
        out += ["", "# --- Roaming warlord ---", "set_country_flag = sc_nomadic",
                f"set_variable = {{ warband_supplies = {n.get('supplies', 50)} }}"]
    if n.get("extra"):
        out += ["", n["extra"].strip()]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- flags
W, H = 820, 520


def draw_flag(spec):
    c = [tuple(x) for x in spec.get("colors", [[128, 128, 128]])]
    c2 = lambda i: c[i % len(c)]
    im = Image.new("RGBA", (W, H), c2(0) + (255,))
    d = ImageDraw.Draw(im)
    p = spec.get("pattern", "plain")
    if p == "horizontal":
        for i, col in enumerate(c):
            d.rectangle([0, H * i // len(c), W, H * (i + 1) // len(c)], fill=col)
    elif p == "vertical":
        for i, col in enumerate(c):
            d.rectangle([W * i // len(c), 0, W * (i + 1) // len(c), H], fill=col)
    elif p == "diagonal":
        d.polygon([(0, H), (W, 0), (W, H)], fill=c2(1))
    elif p == "triangle":
        d.polygon([(0, 0), (W * 0.45, H / 2), (0, H)], fill=c2(1))
    elif p == "cross":
        d.rectangle([0, H * 0.4, W, H * 0.6], fill=c2(1))
        d.rectangle([W * 0.3, 0, W * 0.3 + H * 0.2, H], fill=c2(1))
    elif p == "band":
        d.rectangle([0, H * 0.36, W, H * 0.64], fill=c2(1))
        d.rectangle([0, H * 0.44, W, H * 0.56], fill=c2(2))
    elif p == "mountain":
        d.polygon([(160, 430), (410, 110), (660, 430)], fill=c2(1))
        d.polygon([(330, 210), (410, 110), (490, 210)], fill=c2(2))
    elif p == "saltire":
        d.line([0, 0, W, H], fill=c2(1), width=90)
        d.line([0, H, W, 0], fill=c2(1), width=90)
    elif p == "chevron":
        d.polygon([(0, 0), (W * 0.5, H * 0.5), (0, H), (W * 0.2, H * 0.5)], fill=c2(1))
        d.polygon([(W * 0.3, 0), (W * 0.8, H * 0.5), (W * 0.3, H), (W * 0.5, H * 0.5)], fill=c2(1))
    return im


def write_flags(n):
    custom = ROOT / "gfx" / "flags" / "custom" / f"{n['tag']}.tga"
    im = Image.open(custom).convert("RGBA").resize((W, H)) if custom.exists() else draw_flag(n.get("flag", {}))
    for sub, size in (("", (82, 52)), ("medium", (41, 26)), ("small", (10, 7))):
        d = ROOT / "gfx" / "flags" / sub if sub else ROOT / "gfx" / "flags"
        d.mkdir(parents=True, exist_ok=True)
        im.resize(size, Image.LANCZOS).save(d / f"{n['tag']}.tga")


# ---------------------------------------------------------------- main
def main():
    nations = tomllib.loads(SRC.read_text(encoding="utf-8"))["nation"]
    validate(nations)
    tags = [n["tag"] for n in nations]

    # country tags
    lines = [GEN]
    for n in nations:
        lines.append(f'{n["tag"]} = "countries/SC {safe_filename(n["name"])}.txt"\t# {n.get("group", "")}')
    (ROOT / "common/country_tags/sc_countries.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # country files + history (clear old generated ones first)
    cdir, hdir = ROOT / "common/countries", ROOT / "history/countries"
    for f in cdir.glob("SC *.txt"):
        f.unlink()
    for f in hdir.glob("*.txt"):
        if f.name[:3] in tags or f.read_text(encoding="utf-8", errors="ignore").startswith(GEN[:20]):
            f.unlink()
    for n in nations:
        culture = n.get("culture", "western")
        (cdir / f"SC {safe_filename(n['name'])}.txt").write_text(
            f"{GEN}graphical_culture = {culture}_european_gfx\ngraphical_culture_2d = {culture}_european_2d\n"
            f"color = {{ {' '.join(map(str, n['color']))} }}\n", encoding="utf-8")
        (hdir / f"{n['tag']} - {safe_filename(n['name'])}.txt").write_text(history(n), encoding="utf-8")

    # characters
    lines = [GEN, "characters = {"]
    for n in nations:
        if n.get("leader"):
            sub = n.get("sub_ideology", DEFAULT_SUB[n["ideology"]])
            lines += [f"\t{n['leader']['key']} = {{", f"\t\tname = {n['leader']['key']}",
                      f"\t\tcountry_leader = {{ ideology = {sub} expire = \"1975.1.1.1\" id = -1 }}", "\t}"]
    lines.append("}")
    (ROOT / "common/characters/sc_characters.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # starting armies
    lines = [GEN, "sc_spawn_starting_armies = {"]
    for n in nations:
        if not n.get("divisions"):
            continue
        lines += [f"\t{n['tag']} = {{", "\t\tif = { limit = { exists = yes }"]
        for d in n["divisions"]:
            lines.append(f'\t\t\tcreate_unit = {{ division = "name = \\"{d}\\" division_template = \\"{n["template"]["name"]}\\" '
                         f'start_experience_factor = {n.get("experience", 0.3)}" owner = {n["tag"]} }}')
        lines += ["\t\t}", "\t}"]
    lines.append("}")
    (ROOT / "common/scripted_effects/sc_generated_armies.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # localisation (UTF-8 with BOM)
    lines = ["l_english:", f" # {GEN.strip('# ').strip()}"]
    for n in nations:
        t, name, de, adj = n["tag"], n["name"], n.get("def", n["name"]), n.get("adj", n["name"])
        lines.append(f" # --- {name} ---")
        lines += [f' {t}:0 "{esc(name)}"', f' {t}_DEF:0 "{esc(de)}"', f' {t}_ADJ:0 "{esc(adj)}"']
        for i in IDEOLOGIES:
            lines += [f' {t}_{i}:0 "{esc(name)}"', f' {t}_{i}_DEF:0 "{esc(de)}"', f' {t}_{i}_ADJ:0 "{esc(adj)}"']
        if n.get("desc"):
            lines.append(f' {t}_GAMEPLAY_DESC:0 "{esc(n["desc"])}"')
        if n.get("leader"):
            lines.append(f' {n["leader"]["key"]}:0 "{esc(n["leader"]["name"])}"')
    (ROOT / "localisation/english/sc_nations_l_english.yml").write_text("\n".join(lines) + "\n", encoding="utf-8-sig")

    # flags
    for n in nations:
        write_flags(n)

    # docs
    rows = ["# Nations (generated from setup/nations.toml)", "",
            "| Tag | Name | Group | Ideology | Leader | Divisions | Roaming |", "|---|---|---|---|---|---|---|"]
    for n in sorted(nations, key=lambda n: (n.get("group", ""), n["tag"])):
        rows.append(f"| {n['tag']} | {n['name']} | {n.get('group', '')} | {n['ideology']} ({n.get('sub_ideology', DEFAULT_SUB[n['ideology']])}) "
                    f"| {n.get('leader', {}).get('name', '—')} | {len(n.get('divisions', []))} | {'yes' if n.get('nomadic') else ''} |")
    rows += [""]
    for n in nations:
        if n.get("desc"):
            rows += [f"### {n['tag']}: {n['name']}", "", n["desc"].replace("§Y", "**").replace("§!", "**"), ""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/NATIONS.md").write_text("\n".join(rows), encoding="utf-8")

    print(f"Generated files for {len(nations)} nations: {' '.join(tags)}")


if __name__ == "__main__":
    main()
